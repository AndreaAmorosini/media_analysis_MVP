
"""PressKG Identity Attribute Extraction v1.

Extracts grounded attribute candidates and contextual links
from occurrence profiles generated by profiles.py.

Read-only, offline, deterministic.

No Neo4j writes, no LLM calls, no entity merging.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import unicodedata

from collections import Counter
from contextlib import ExitStack
from pathlib import Path


VERSION = "identity-attributes-v1"
SOURCE_VERSION = "identity-profiles-v1"

# These predicates can describe an identifying attribute
# when the occurrence is the SUBJECT of the validated fact.
#
# Every value remains a candidate, never a verified
# identity constraint at this stage.
ATTRIBUTE_PREDICATES = {
    "WORKS_FOR": "employer",
    "WORKS_AT": "workplace",
    "LOCATED_IN": "geographic_context",
    "LOCATED_AT": "location_or_address",
    "OPERATES_IN": "operational_area",
    "REPRESENTS": "represented_entity",
    "PRESIDES_OVER": "presided_entity",
}

# Other predicates provide contextual evidence. They are
# not sufficient to establish an identity match.
CONTEXT_PREDICATES = {
    "COLLABORATES_WITH",
    "COORDINATES_WITH",
    "FUNDS",
    "FINANCED_BY",
    "MANAGES",
    "ORGANIZES",
    "PARTICIPATES_IN",
    "IMPLEMENTS",
    "EXECUTES",
    "LAUNCHES",
    "PROMOTES",
    "SUPPORTS",
    "PROVIDES",
    "SERVES",
    "ISSUES",
    "SIGNS",
    "PRESENT_AT",
    "PRESENTS_AT",
    "WORKS_ON",
    "INVESTS_IN",
}

LEGAL_FORMS = (
    ("S.p.A.", r"(?<!\w)s\.?\s*p\.?\s*a\.?(?!\w)"),
    ("S.r.l.", r"(?<!\w)s\.?\s*r\.?\s*l\.?(?!\w)"),
    ("S.c.a.r.l.", r"(?<!\w)s\.?\s*c\.?\s*a\.?\s*r\.?\s*l\.?(?!\w)"),
    ("S.n.c.", r"(?<!\w)s\.?\s*n\.?\s*c\.?(?!\w)"),
    ("S.a.s.", r"(?<!\w)s\.?\s*a\.?\s*s\.?(?!\w)"),
)

NON_IDENTITY_STATUSES = {
    "NON_IDENTITY",
    "COLLECTIVE_HOLD",
}

COMPOSITE_HOLD_STATUSES = {
    "COMPOSITE_MENTION_HOLD",
}

ALLOWED_SCOPES = {
    "mention_occurrence",
    "decomposed_component",
}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def normalize(value):
    return " ".join(
        unicodedata.normalize(
            "NFKC",
            str(value or ""),
        ).casefold().split()
    )


def digest(value):
    raw = json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")

    return hashlib.sha256(
        raw
    ).hexdigest()


def jsonline(value):
    return json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
    ) + "\n"


def read_json(path):
    return json.loads(
        Path(path).read_text(
            encoding="utf-8"
        )
    )


def iter_jsonl(path):
    with Path(path).open(
        encoding="utf-8"
    ) as handle:
        for number, line in enumerate(handle, 1):
            if not line.strip():
                continue

            try:
                yield json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(
                    f"{path}:{number}: {exc}"
                ) from exc


def file_sha256(path):
    digest_ = hashlib.sha256()

    with Path(path).open("rb") as handle:
        for chunk in iter(
            lambda: handle.read(1024 * 1024),
            b"",
        ):
            digest_.update(chunk)

    return digest_.hexdigest()


def validate_source(directory):
    directory = Path(directory)

    summary = read_json(
        directory / "summary.json"
    )

    require(
        summary["version"] == SOURCE_VERSION,
        "Unexpected identity profile version",
    )

    names = {
        "mention_profiles.jsonl":
            "mention_profiles_sha256",
        "component_profiles.jsonl":
            "component_profiles_sha256",
        "relation_evidence.jsonl":
            "relation_evidence_sha256",
    }

    for filename, key in names.items():
        require(
            file_sha256(directory / filename)
            == summary[key],
            f"Source checksum mismatch: {filename}",
        )

    require(
        summary["graph_writes"] == 0
        and summary["identity_merges"] == 0
        and summary["approved_relations"] == 0,
        "Source has unauthorized changes",
    )

    return summary


def contains_surface(text, surface):
    """Boundary-aware normalized surface match.

    A lexical match is not semantic proof of identity.
    """

    text = normalize(text)
    surface = normalize(surface)

    if not text or not surface:
        return False

    pattern = (
        r"(?<!\w)"
        + re.escape(surface)
        + r"(?!\w)"
    )

    return re.search(pattern, text) is not None


def quote_coverage(profile):
    """Check whether the quote names both fact arguments.

    This measures lexical support, not semantic entailment.
    """

    quote = (
        profile["provenance"].get("supporting_span")
        or profile["provenance"].get("original_quote")
        or ""
    )

    source = profile["surface"]
    target = (
        profile["fact_context"]
        .get("counterpart_name")
        or ""
    )

    source_found = contains_surface(
        quote,
        source,
    )

    target_found = contains_surface(
        quote,
        target,
    )

    if source_found and target_found:
        status = "BOTH_ARGUMENTS_LEXICAL"

    elif source_found or target_found:
        status = "PARTIAL_ARGUMENTS_LEXICAL"

    else:
        status = "NO_ARGUMENTS_LEXICAL"

    return {
        "status": status,
        "source_found": source_found,
        "target_found": target_found,
        "quote": quote,
        "quote_sha256": hashlib.sha256(
            quote.encode("utf-8")
        ).hexdigest(),
        "quote_field": (
            "supporting_span"
            if profile["provenance"].get(
                "supporting_span"
            )
            else "original_quote"
        ),
    }


def lexical_signals(profile):
    """Extract signals intrinsic to this particular surface."""

    surface = profile["surface"]
    kind = profile["source_kind"]

    results = []

    if kind in {
        "Company",
        "Organization",
        "NonProfitOrganization",
    }:
        for form, pattern in LEGAL_FORMS:
            if re.search(
                pattern,
                surface,
                re.IGNORECASE,
            ):
                results.append({
                    "profile_id": profile["profile_id"],
                    "signal": "legal_form",
                    "value": form,
                    "surface": surface,
                    "origin": "name_surface",
                    "strength": "lexical_hint",
                    "identity_verified": False,
                })
                break

    return results


def make_relation_record(profile):
    """Create one candidate relationship from the subject side.

    The opposite mention will be processed as a separate
    occurrence profile, but won't duplicate the same fact.
    """

    if profile["profile_scope"] != "mention_occurrence":
        return None

    if profile["role"] != "subject":
        return None

    context = profile["fact_context"]

    predicate = context.get("predicate")

    if (
        not isinstance(predicate, str)
        or predicate in {"OTHER", ""}
    ):
        return None

    target = context.get(
        "counterpart_name"
    )

    if not isinstance(target, str) or not target.strip():
        return None

    if not profile["surface"].strip():
        return None

    coverage = quote_coverage(profile)

    if predicate in ATTRIBUTE_PREDICATES:
        category = "identity_attribute_candidate"
        attribute = ATTRIBUTE_PREDICATES[predicate]

    elif predicate in CONTEXT_PREDICATES:
        category = "contextual_relation"
        attribute = None

    else:
        return None

    status = profile["resolution_status"]

    # Composite and collective subjects cannot inherit
    # a fact's predicate as individually split identities.
    if status in COMPOSITE_HOLD_STATUSES:
        disposition = "HELD_COMPOSITE_SCOPE"

    elif status in NON_IDENTITY_STATUSES:
        disposition = "HELD_NON_IDENTITY"

    elif coverage["status"] != "BOTH_ARGUMENTS_LEXICAL":
        disposition = "HELD_LEXICAL_EVIDENCE"

    else:
        disposition = "PROFILE_EVIDENCE_CANDIDATE"

    # Even a lexically grounded attribute is not approved
    # for automatic merging at this stage.
    return {
        "evidence_id": (
            f"{profile['fact_id']}:{predicate}"
        ),
        "subject_profile_id": profile["profile_id"],
        "fact_id": profile["fact_id"],
        "claim_id": profile["claim_id"],
        "article_id": profile["article_id"],

        "subject_surface": profile["surface"],
        "subject_kind": profile["source_kind"],

        "predicate": predicate,
        "object_surface": target,
        "object_kind": context.get("counterpart_kind"),

        "category": category,
        "attribute_kind": attribute,

        "disposition": disposition,
        "quote_coverage": coverage["status"],

        "evidence": {
            "quote": coverage["quote"],
            "quote_field": coverage["quote_field"],
            "quote_sha256": coverage["quote_sha256"],
            "source_found": coverage["source_found"],
            "target_found": coverage["target_found"],
            "article_title": (
                profile["provenance"].get(
                    "article_title"
                )
            ),
            "article_source": (
                profile["provenance"].get(
                    "article_source"
                )
            ),
            "publication_date": (
                profile["provenance"].get(
                    "publication_date"
                )
            ),
            "representation": (
                context.get("representation")
            ),
            "modality": context.get("modality"),
            "temporal_status": (
                context.get("temporal_status")
            ),
        },

        "attribute_verified": False,
        "match_constraint_approved": False,
        "fact_expansion_allowed": False,
    }


def process_profile(profile):
    require(
        profile["profile_scope"] in ALLOWED_SCOPES,
        "Invalid profile scope",
    )

    require(
        profile["profile_id"]
        and profile["mention_id"]
        and profile["fact_id"]
        and profile["article_id"],
        "Incomplete provenance",
    )

    require(
        profile["canonical_id"] is None
        and profile["merge_approved"] is False,
        "Unexpected resolved identity",
    )

    signals = lexical_signals(profile)

    relation = make_relation_record(profile)

    return signals, relation


def run(args):
    source_dir = Path(args.source_dir)
    source_summary = validate_source(source_dir)

    out = Path(args.out_dir)

    require(
        not out.exists(),
        "Output directory already exists. "
        "Choose a fresh directory.",
    )

    out.mkdir(
        parents=True,
        exist_ok=False,
    )

    files = {
        "attributes":
            out / "attribute_evidence.jsonl",
        "context":
            out / "context_relations.jsonl",
        "lexical":
            out / "lexical_signals.jsonl",
        "summary":
            out / "summary.json",
    }

    counts = Counter()
    dispositions = Counter()
    attributes = Counter()
    lexical_types = Counter()

    seen_profiles = set()
    seen_facts = set()

    with ExitStack() as stack:
        handles = {
            key: stack.enter_context(
                path.open(
                    "w",
                    encoding="utf-8",
                )
            )
            for key, path in files.items()
            if key != "summary"
        }

        for filename, expected_scope in (
            (
                "mention_profiles.jsonl",
                "mention_occurrence",
            ),
            (
                "component_profiles.jsonl",
                "decomposed_component",
            ),
        ):
            for profile in iter_jsonl(
                source_dir / filename
            ):
                require(
                    profile["profile_scope"]
                    == expected_scope,
                    "Profile scope/file mismatch",
                )

                pid = profile["profile_id"]

                require(
                    pid not in seen_profiles,
                    f"Duplicate profile: {pid}",
                )

                seen_profiles.add(pid)

                counts[expected_scope] += 1

                signals, relation = process_profile(
                    profile
                )

                for signal in signals:
                    handles["lexical"].write(
                        jsonline(signal)
                    )
                    lexical_types[signal["signal"]] += 1
                    counts["lexical_signals"] += 1

                if relation is None:
                    continue

                # Each validated fact must produce at most
                # one extracted relationship in this module.
                require(
                    profile["fact_id"] not in seen_facts,
                    "Duplicate fact relationship",
                )

                seen_facts.add(profile["fact_id"])

                key = (
                    "attributes"
                    if relation["category"]
                    == "identity_attribute_candidate"
                    else "context"
                )

                handles[key].write(
                    jsonline(relation)
                )

                counts[key] += 1
                dispositions[
                    relation["disposition"]
                ] += 1

                if relation["attribute_kind"]:
                    attributes[
                        relation["attribute_kind"]
                    ] += 1

    require(
        counts["mention_occurrence"]
        == source_summary["mention_profiles"],
        "Mention profile coverage mismatch",
    )

    require(
        counts["decomposed_component"]
        == source_summary["component_profiles"],
        "Component profile coverage mismatch",
    )

    result = {
        "version": VERSION,
        "source_version": SOURCE_VERSION,
        "source_batch_key":
            source_summary["source_batch_key"],
        "source_mention_sha256":
            source_summary[
                "mention_profiles_sha256"
            ],
        "source_component_sha256":
            source_summary[
                "component_profiles_sha256"
            ],

        "mention_profiles_processed":
            counts["mention_occurrence"],
        "component_profiles_processed":
            counts["decomposed_component"],

        "attribute_candidates":
            counts["attributes"],
        "contextual_relations":
            counts["context"],
        "lexical_signals":
            counts["lexical_signals"],

        "disposition_counts":
            dict(sorted(dispositions.items())),
        "attribute_kind_counts":
            dict(sorted(attributes.items())),
        "lexical_signal_counts":
            dict(sorted(lexical_types.items())),

        "attribute_evidence_sha256":
            file_sha256(files["attributes"]),
        "context_relations_sha256":
            file_sha256(files["context"]),
        "lexical_signals_sha256":
            file_sha256(files["lexical"]),

        "relation_proposals_preserved_upstream":
            source_summary["relation_proposals"],

        "canonical_entities": 0,
        "identity_merges": 0,
        "approved_attributes": 0,
        "approved_relations": 0,
        "graph_writes": 0,
    }

    files["summary"].write_text(
        json.dumps(
            result,
            ensure_ascii=False,
            sort_keys=True,
            indent=2,
        ) + "\n",
        encoding="utf-8",
    )

    print(
        json.dumps(
            result,
            ensure_ascii=False,
            indent=2,
        )
    )


def main():
    parser = argparse.ArgumentParser(
        description=__doc__
    )

    parser.add_argument(
        "--source-dir",
        default=(
            "output/resolution/"
            "identity-profiles-v1"
        ),
    )

    parser.add_argument(
        "--out-dir",
        default=(
            "output/resolution/"
            "identity-attributes-v1"
        ),
    )

    run(parser.parse_args())


if __name__ == "__main__":
    main()
